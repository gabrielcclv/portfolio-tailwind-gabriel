/**
 * Grade 3: Implementación de Portfolio Scroll con Tailwind + GSAP Modular
 * Refactorizado para integración con enrutador basado en hash
 *
 * Este módulo proporciona animaciones de desplazamiento y funcionalidad de navegación
 * que puede inicializarse cuando se monta una vista y limpiarse al navegar.
 */
import gsap from 'gsap';
import { ScrollToPlugin } from 'gsap/ScrollToPlugin';
import { ScrollTrigger } from 'gsap/ScrollTrigger';

// Registrar plugins de GSAP una vez al cargar el módulo
gsap.registerPlugin(ScrollTrigger, ScrollToPlugin);

// ==========================================================================
// 1. Configuración
// ==========================================================================

const config = {
	reducedMotion: window.matchMedia('(prefers-reduced-motion: reduce)').matches,
	breakpoints: {
		sm: 640,
		md: 768,
		lg: 1024,
	},
};

// ==========================================================================
// 2. Módulo de Animación
// ==========================================================================

const animations = {
	/**
	 * Inicializar animaciones de GSAP dentro de un elemento contenedor
	 * @param {HTMLElement} container - El elemento contenedor para limitar el alcance de las animaciones
	 */
	init(container = document) {
		if (config.reducedMotion) {
			console.log('⚠️ Preferencia de movimiento reducido detectada — animaciones deshabilitadas');
			this.showAllElements(container);
			return;
		}

		this.initFadeUp(container);
		this.initParallax(container);
		this.initProjectCards(container);

		console.log('✨ Animations initialized');
	},

	/**
	 * Mostrar todos los elementos animados inmediatamente (para movimiento reducido)
	 * @param {HTMLElement} container - El elemento contenedor para limitar el alcance de consultas
	 */
	showAllElements(container) {
		container.querySelectorAll('[data-animate]').forEach((el) => {
			el.style.opacity = '1';
			el.style.transform = 'none';
		});
	},

	/**
	 * Animaciones de desvanecimiento hacia arriba para elementos con data-animate="fade-up"
	 * @param {HTMLElement} container - El elemento contenedor para limitar el alcance de consultas
	 */
	initFadeUp(container) {
		const elements = gsap.utils.toArray(container.querySelectorAll('[data-animate="fade-up"]'));

		elements.forEach((el) => {
			// Establecer estado inicial
			gsap.set(el, { opacity: 0, y: 40 });

			gsap.to(el, {
				opacity: 1,
				y: 0,
				duration: 0.8,
				ease: 'power2.out',
				scrollTrigger: {
					trigger: el,
					start: 'top 85%',
					toggleActions: 'play none none none',
				},
			});
		});
	},

	/**
	 * Efecto de paralaje para elementos con atributo data-parallax
	 * @param {HTMLElement} container - El elemento contenedor para limitar el alcance de consultas
	 */
	initParallax(container) {
		const parallaxElements = container.querySelectorAll('[data-parallax]');

		parallaxElements.forEach((el) => {
			const speed = parseFloat(el.dataset.parallax) || 0.2;

			gsap.to(el, {
				yPercent: -100 * speed,
				ease: 'none',
				scrollTrigger: {
					trigger: el.parentElement,
					start: 'top bottom',
					end: 'bottom top',
					scrub: true,
				},
			});
		});
	},

	/**
	 * Revelación escalonada para tarjetas de proyecto
	 * @param {HTMLElement} container - El elemento contenedor para limitar el alcance de consultas
	 */
	initProjectCards(container) {
		// Establecer estado inicial explícitamente para una posición de inicio consistente
		const cards = gsap.utils.toArray(container.querySelectorAll('.project-card'));
		gsap.set(cards, { y: 50, opacity: 0 });

		ScrollTrigger.batch(container.querySelectorAll('.project-card'), {
			onEnter: (batch) => {
				gsap.to(batch, {
					y: 0,
					opacity: 1,
					duration: 0.7,
					stagger: 0.12,
					ease: 'power2.out',
				});
			},
			start: 'top 90%',
			once: true,
		});
	},

	/**
	 * Limpiar todas las instancias de ScrollTrigger y animaciones
	 */
	destroy() {
		ScrollTrigger.getAll().forEach((trigger) => trigger.kill());
		gsap.killTweensOf('*');
	},
};

