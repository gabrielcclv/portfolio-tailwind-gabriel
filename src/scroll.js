/**
 * Inicializar animaciones de desplazamiento y navegación para una vista
 * @param {HTMLElement} container - El elemento contenedor (típicamente el elemento app)
 */
export function initScrollView(container) {
	// Desplazarse al inicio cuando se carga la vista
	window.scrollTo({ top: 0, behavior: 'auto' });

	// Inicializar animaciones
	animations.init(container);

	// Inicializar navegación (menú se inicializa globalmente, pero características de desplazamiento son por vista)
	navigation.init(container);

	// Actualizar ScrollTrigger después de un pequeño retraso para asegurar que el DOM esté listo
	// y después de que las imágenes se carguen
	setTimeout(() => {
		ScrollTrigger.refresh();
	}, 100);

	window.addEventListener(
		'load',
		() => {
			ScrollTrigger.refresh();
		},
		{ once: true }
	);

	console.log('🚀 Scroll view initialized');
}

/**
 * Limpiar animaciones de desplazamiento y navegación al abandonar la vista
 */
export function cleanupScrollView() {
	animations.destroy();
	// No destruir navegación - debe persistir entre rutas
	// navigation.destroy();
	console.log('🧹 Vista de desplazamiento limpiada');
}

/**
 * Inicializar menú de navegación (debe llamarse una sola vez globalmente)
 */
export function initNavigation() {
	navigation.init(document);
	console.log('🧭 Menú de navegación inicializado');
}
/**
 * Inicializar funcionalidad de alternancia de vista de proyectos
 */
export function initProjectsToggle(container = document) {
	const gridBtn = container.getElementById ? container.getElementById('grid-view-btn') : container.querySelector('#grid-view-btn');
	const listBtn = container.getElementById ? container.getElementById('list-view-btn') : container.querySelector('#list-view-btn');
	const projectsGrid = container.getElementById ? container.getElementById('projects-grid') : container.querySelector('#projects-grid');

	if (!gridBtn || !listBtn || !projectsGrid) {
		return;
	}

	let isGridView = true;

	const updateButtonStyles = (active, inactive) => {
		active.classList.add('bg-white', 'dark:bg-gray-800', 'text-gray-900', 'dark:text-white', 'shadow-md');
		active.classList.remove('text-gray-600', 'dark:text-gray-400');
		
		inactive.classList.remove('bg-white', 'dark:bg-gray-800', 'text-gray-900', 'dark:text-white', 'shadow-md');
		inactive.classList.add('text-gray-600', 'dark:text-gray-400');
	};

	gridBtn.addEventListener('click', (e) => {
		e.preventDefault();
		if (isGridView) return;
		isGridView = true;
		
		projectsGrid.className = 'grid md:grid-cols-2 lg:grid-cols-3 gap-6';
		updateButtonStyles(gridBtn, listBtn);

		container.querySelectorAll('.project-card').forEach(card => {
			card.classList.remove('md:flex', 'gap-4', 'flex-col', 'md:flex-row');
		});
	});

	listBtn.addEventListener('click', (e) => {
		e.preventDefault();
		if (!isGridView) return;
		isGridView = false;
		
		projectsGrid.className = 'grid md:grid-cols-2 lg:grid-cols-2 gap-4';
		updateButtonStyles(listBtn, gridBtn);

		container.querySelectorAll('.project-card').forEach(card => {
			card.classList.add('md:flex', 'gap-4');
			card.classList.add('flex-col', 'md:flex-row');
		});
	});

	console.log('🎨 Alternancia de proyectos inicializada');
}